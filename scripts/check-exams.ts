import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve, sep } from "node:path";
import { migrate } from "drizzle-orm/better-sqlite3/migrator";
import { getDb } from "../src/db";
import { examSets, problems, problemAttempts } from "../src/db/schema";
import { listExams, listExamProblems, findProblem, listProblems } from "../src/lib/problems";
import { listWrongAnswers } from "../src/lib/reviews";
import { listAttempts } from "../src/lib/attempts";
import { getWeaknesses } from "../src/lib/weaknesses";
import { examCountdown } from "../src/lib/exam-countdown";

const root = process.cwd();
const temporary = mkdtempSync(join(tmpdir(), "jungsil-exams-"));
process.chdir(temporary);
const db = getDb();
try {
  migrate(db, { migrationsFolder: join(root, "drizzle") });
  const exam = (round: number) => db.insert(examSets).values({ certification: "TEST", examYear: 2026, examRound: round, examDate: "2026-07-19", title: "Test", questionCount: 3, sourceType: "MANUAL" }).returning().get();
  const second = exam(2), first = exam(1), empty = exam(3);
  const question = (examSetId: string, questionNumber: number, verified = true) => db.insert(problems).values({ examSetId, questionNumber, title: "Fixture", content: "Test", answer: "SECRET_ANSWER", explanation: "SECRET_EXPLANATION", questionType: "SHORT_ANSWER", topic: "TEST", difficulty: "EASY", sourceType: "MANUAL", sourceName: "TEST", verificationStatus: verified ? "VERIFIED" : "DRAFT" }).returning().get();
  const q2 = question(first.id, 2), q1 = question(first.id, 1);
  question(first.id, 3, false);
  question(second.id, 1);
  for (let i = 0; i < 2; i++) db.insert(problemAttempts).values({ problemId: q1.id, userAnswer: "wrong", correct: false, score: 0, attemptContext: "PAST_EXAM_SESSION" }).run();
  const cards = listExams();
  assert.deepEqual(cards.map(e => e.id), [first.id, second.id, empty.id]);
  assert.equal(cards[0].available, 2);
  assert.equal(cards[0].expected, 3);
  assert.equal(cards[0].solved, 1, "Repeated submissions count once");
  assert.equal(cards[2].available, 0);
  const rows = listExamProblems(first.id);
  assert.deepEqual(rows.map(q => q.id), [q1.id, q2.id]);
  assert.deepEqual(rows.map(q => q.solved), [true, false]);
  assert.equal(rows.find(q => !q.solved)?.id, q2.id);
  assert.ok(!JSON.stringify(rows).includes("SECRET"));
  assert.deepEqual(listExamProblems("missing"), []);
  assert.deepEqual(listExamProblems("' OR 1=1--"), []);
  const originalTitle = "2026년 1회 · PDF 15번 · 정보보호 관리체계 약자";
  const displayTitle = "2026년 1회 15번 · 정보보호 관리체계 약자";
  db.$client.prepare("UPDATE problems SET title = ? WHERE id = ?").run(originalTitle, q1.id);
  assert.equal(findProblem(q1.id)?.title, displayTitle);
  assert.equal(listProblems(new URLSearchParams()).find(q => q.id === q1.id)?.title, displayTitle);
  assert.equal(listExamProblems(first.id)[0].title, displayTitle);
  assert.equal(listWrongAnswers(new URLSearchParams())[0].title, displayTitle);
  assert.equal(listAttempts(new URLSearchParams())[0].problem.title, displayTitle);
  assert.equal(getWeaknesses().recommendations[0].title, displayTitle + " 다시 풀기");
  assert.equal(findProblem(q2.id)?.title, "Fixture");
  assert.equal((db.$client.prepare("SELECT title FROM problems WHERE id = ?").get(q1.id) as { title: string }).title, originalTitle);
  assert.equal(examCountdown(new Date("2026-09-30T00:00:00+09:00")).days, 25);
  assert.equal(examCountdown(new Date("2026-10-24T14:59:59Z")).days, 1);
  assert.equal(examCountdown(new Date("2026-10-24T15:00:00Z")).days, 0);
  assert.equal(examCountdown(new Date("2026-10-26T00:00:00+09:00")).days, -1);
  assert.equal(examCountdown(new Date("2026-09-01T00:00:00+09:00")).progress, 0);
  assert.equal(examCountdown(new Date("2026-11-01T00:00:00+09:00")).progress, 100);
  console.log("PASS: grouped exams, numerical order, resume, unique progress, draft/answer protection and Korea midnight countdown.");
} finally {
  db.$client.close();
  process.chdir(root);
  assert.ok(resolve(temporary).startsWith(resolve(tmpdir()) + sep));
  rmSync(temporary, { recursive: true, force: true });
}
